function aiAnswer(q){
  const s = q.toLowerCase();
  const role = currentUser.role;
  if((role==='tenant'||role==='partner'||role==='crm'||role==='hr'||role==='accountant') && /generat.*invoice|create.*invoice|issue.*invoice|evict/.test(s)){
    return {text:'🔒 Permission denied — your role ('+roleOf().label+') cannot perform this action. Ask about your lease, PRCA rights, maintenance liability, or tax questions instead.', tools:['permission_check()']};
  }
  const L = DB.leases, I = DB.invoices, P = DB.properties;
  let m = s.match(/invoice\s+(for\s+)?(l-\d+)/i);
  if(m && /generat|create|make|issue|bill/.test(s)){
    const l = L.find(x=>x.id.toLowerCase()===m[2].toLowerCase());
    if(!l) return {text:'Lease '+m[2]+' not found. Active leases: '+L.filter(x=>x.status==='Active').map(x=>x.id).join(', '), tools:[]};
    const td = tdsFor(l);
    const gross = l.rent, tds = Math.round(gross*td.rate), net = gross-tds;
    const inv = {id:'INV-2026-'+String(I.length+1).padStart(3,'0'), lease:l.id, month:today().slice(0,7), gross, tdsRate:td.rate, tds, net, status:'Unpaid'};
    I.push(inv); saveDB();
    return {text:'✅ Generated '+inv.id+' for '+l.id+' — gross '+fmt(gross)+(td.rate?', TDS '+fmt(tds)+' ('+td.section+'), net '+fmt(net):'')+'. Tenant: '+tenantById(l.tenant).name+'.', tools:['generate_invoice()']};
  }
  if(/report|ticket|issue|plumbing|leak|maintenance/.test(s) && /leak|plumb|roof|crack|fix|repair|maintenance|broken|pump/.test(s)){
    const u = DB.units[0];
    const desc = s.replace(/.*?(report|ticket|issue)\s*/i,'').slice(0,80) || 'Reported via AI chat';
    const liab = resolveLiability(u.id, desc);
    DB.tickets.push({id:uid('MT'), unit:u.id, desc, reported:today(), liability:liab, status:'Open', contractor:'', cost:0, note:'via KR'});
    saveDB();
    return {text:'🔧 Ticket '+DB.tickets[DB.tickets.length-1].id+' created for '+unitLabel(u)+'. Liability resolver → '+liab+' responsibility (per lease + PRCA defaults).', tools:['create_maintenance_ticket()','resolve_liability()']};
  }
  if(/rent due|outstanding|who owes|unpaid/.test(s)){
    const due = I.filter(v=>v.status==='Unpaid'||v.status==='Overdue');
    if(!due.length) return {text:'Nothing outstanding — all invoices settled 🎉', tools:[]};
    const lines = due.map(v=>{ const l=L.find(x=>x.id===v.lease); return v.id+' · '+tenantById(l.tenant).name+' · '+fmt(v.net)+(v.tds?' (net of TDS)':''); }).join('\n');
    return {text:'You have '+due.length+' outstanding invoice(s), total '+fmt(due.reduce((s,v)=>s+v.net,0))+':\n'+lines, tools:['query_invoices()']};
  }
  if(/holding tax|annual value/.test(s)){
    const p = P[0];
    const r = holdingTaxCalc(p);
    return {text:'Holding tax for '+p.name+' ('+p.jurisdiction+'):\n1) Gross Annual Rent: '+fmt(r.gar)+'\n2) − Maintenance allowance (2 mo): '+fmt(r.allowance)+'\n3) − Mortgage interest: '+fmt(r.interest)+'\n4) Net Annual Value: '+fmt(r.nav)+' → tax ≈ '+fmt(r.tax)+'/yr at '+(r.rate*100).toFixed(1)+'%.', tools:['calc_holding_tax()']};
  }
  if(/tds|withholding/.test(s)){
    const corp = L.filter(l=>tenantById(l.tenant)?.kind==='Corporate' && (l.status==='Active'||l.status==='Pending Registration'));
    if(!corp.length) return {text:'No corporate tenancies — TDS not applicable on individual rent.', tools:[]};
    const lines = corp.map(l=>{ const td=tdsFor(l); return l.id+' · '+tenantById(l.tenant).name+' · '+(td.rate*100).toFixed(0)+'% ('+td.section+')'; }).join('\n');
    return {text:'TDS applies to corporate tenants (Income Tax Act 2023):\n'+lines+'\n\nCommercial lease collections: 4% (§128) · general rental: 10% (§109).', tools:['tds_lookup()']};
  }
  if(/advance|deposit|security/.test(s)){
    const bad = L.filter(l=>l.residential && l.advance>l.rent);
    if(!bad.length) return {text:'All residential leases comply — advance ≤ 1 month rent (PRCA 1991 §10/§23). ✓', tools:['prca_check()']};
    return {text:'⚠ '+bad.length+' residential lease(s) exceed the 1-month advance cap:\n'+bad.map(l=>l.id+' · '+tenantById(l.tenant).name+' · advance '+fmt(l.advance)+' vs rent '+fmt(l.rent)).join('\n')+'\nRequires rent-controller written consent or commercial override.', tools:['prca_check()']};
  }
  if(/evict|eviction/.test(s)){
    const elig = DB.tenants.map(t=>({t,e:evictionEligible(t.id)})).filter(x=>x.e.eligible);
    if(!elig.length) return {text:'No tenant currently meets the ≥3-month unpaid threshold for §18 eviction grounds. Digital lockouts are never performed.', tools:['eviction_check()']};
    return {text:'⚠ '+elig.map(x=>x.t.name+' ('+x.e.months+' mo unpaid)').join(', ')+' — grounds met. I can generate a compliant §114A notice.', tools:['eviction_check()']};
  }
  if(/liab|who.*(pay|fix|responsible)|roof|structural/.test(s)){
    return {text:'Liability rule (PRCA 1991): structural/maintenance = Landlord; day-to-day = Tenant. Open tickets:\n'+DB.tickets.filter(t=>t.status!=='Closed').map(t=>t.id+' · '+t.desc.slice(0,40)+' → '+t.liability).join('\n'), tools:['resolve_liability()']};
  }
  if(/registr/.test(s)){
    const pr = L.filter(l=>l.status==='Pending Registration');
    return {text: pr.length? '⚠ '+pr.length+' lease(s) pending registration (TPA 1882 §107): '+pr.map(l=>l.id+' ('+leaseMonths(l)+' mo)').join(', ')+'. Ledgers stay inactive until sub-registry docs uploaded.' : 'All leases >12 months have registered instruments ✓', tools:['registration_gate()']};
  }
  if(/legal|law|act|section|prca|tpa|allowed/.test(s)){
    return {text:'⚖️ Under PRCA 1991 §18, a tenant paying allowable rent cannot be summarily evicted; eviction needs a court decree on specific grounds (e.g. 3 months unpaid). §10/§23 cap residential advance at 1 month rent without rent-controller consent. TPA 1882 §107 + Registration Act §17(1)(d) make leases >12 months invalid without a registered instrument.\n\n(Phase 5: full RAG retrieval over statute texts via DeepSeek embeddings.)', tools:['rag_retrieve()']};
  }
  return {text:'I can help with: rent due status · TDS rates · holding tax · PRCA advance/eviction rules · lease registration · maintenance liability · generating invoices & tickets.\n\nTry one of the suggestions above, or ask e.g. "Generate invoice for L-004".', tools:[]};
}

